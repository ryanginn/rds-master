# Create reverse mapping: Unicode to RDS
UNICODE_TO_RDS = {v: k for k, v in RDS_TO_UNICODE.items() if v != 0x0000 or k == 0x00}
# Handle special case: $ (U+0024) should map to 0xAB in RDS, not be missing
UNICODE_TO_RDS[0x0024] = 0xAB  # Dollar sign at correct position


def rds_bytes_to_text(raw, stop_at_cr=True):
    """RDS bytes to Unicode.

    0x0D ends the text - it is the RDS terminator, not a character - and what
    follows it is padding, so by default both are dropped. Remaining control
    codes become spaces: they are not printable and must not reach a display.
    """
    if not raw:
        return ""
    if stop_at_cr:
        end = raw.find(0x0D)
        if end >= 0:
            raw = raw[:end]
    out = []
    for b in raw:
        cp = RDS_TO_UNICODE.get(b, 0x20)
        out.append(chr(cp) if cp >= 0x20 else " ")
    return "".join(out)


def text_to_rds_bytes(text):
    """Unicode to RDS byte codes. Anything outside the set becomes a space."""
    if not text:
        return b""
    return bytes(UNICODE_TO_RDS.get(ord(c), 0x20) for c in text)
